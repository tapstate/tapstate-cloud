package io.tapstate.cloud.iac.config;

import io.tapstate.cloud.cluster.Cluster;
import org.springframework.stereotype.Component;

/**
 * Generates the file content pushed to a Cluster node during provisioning.
 * <p>
 * Output is assembled from text blocks rather than a YAML library: the formats are
 * fixed, small, and contain only controlled values, so direct rendering keeps the
 * dependency surface minimal and the result byte-explicit.
 */
@Component
public class ClusterRuntimeConfigs {

    /** Remote path of the Docker Compose definition. */
    public static final String REMOTE_COMPOSE_PATH = "/opt/tapstate-runtime/docker-compose.yml";

    /** Remote path of the Nginx site configuration. */
    public static final String REMOTE_NGINX_CONF_PATH = "/etc/nginx/conf.d/tapstate-cluster.conf";

    /**
     * Remote path of the Nginx http-context tuning file. The name sorts before the
     * site file, since Nginx builds the server-name hash while reading the site.
     */
    public static final String REMOTE_NGINX_HTTP_CONF_PATH =
        "/etc/nginx/conf.d/00-tapstate-http.conf";

    /** Remote directory holding the centrally managed TLS certificate and key. */
    public static final String REMOTE_NGINX_SSL_DIR = "/etc/nginx/ssl";

    /** Remote path of the full-chain certificate served by Nginx. */
    public static final String REMOTE_NGINX_CERT_PATH =
        REMOTE_NGINX_SSL_DIR + "/tapstate-cluster.crt";

    /** Remote path of the private key matching {@link #REMOTE_NGINX_CERT_PATH}. */
    public static final String REMOTE_NGINX_KEY_PATH =
        REMOTE_NGINX_SSL_DIR + "/tapstate-cluster.key";

    /** Runtime image deployed onto every Cluster node. */
    private static final String RUNTIME_IMAGE = "ghcr.io/tapstate/tapstate-cloud:0.6.0";

    /** Sidecar MongoDB service name and database used when no external Atlas URI is set. */
    private static final String SIDECAR_MONGO_SERVICE = "tapstate-mongo";
    private static final String SIDECAR_DATABASE = "tapstate_cluster";
    private static final String SIDECAR_MONGO_IMAGE = "mongo:7";

    /**
     * Render {@code docker-compose.yml} for the Cluster.
     * <p>
     * The runtime container binds only to the node loopback; external traffic always
     * traverses Nginx. State lives in a named volume so it is independent of the
     * container lifecycle.
     * <p>
     * A blank {@code runtimeAtlasUri} adds a dedicated MongoDB sidecar the runtime
     * uses; a non-blank URI points at externally managed MongoDB without a sidecar.
     */
    public String dockerComposeYaml(Cluster cluster, String controlPlaneBaseUrl,
                                    String runtimeAtlasUri) {
        String clusterId = cluster.getId().toHexString();
        String token = cluster.getSdkStaticToken();
        boolean sidecar = runtimeAtlasUri == null || runtimeAtlasUri.isBlank();
        String atlasUri = sidecar
            ? "mongodb://" + SIDECAR_MONGO_SERVICE + ":27017/" + SIDECAR_DATABASE
            : runtimeAtlasUri;

        String header = "# Cluster runtime stack - generated by the control plane, "
            + "do not edit by hand.\nservices:\n";

        String runtime = """
              tapstate-runtime:
                image: %s
                container_name: tapstate-runtime
                restart: unless-stopped
                ports:
                  - "127.0.0.1:8080:8080"
                environment:
                  SERVER_FORWARD_HEADERS_STRATEGY: native
                  TAPSTATE_CLOUD_BASE_URL: "%s"
                  TAPSTATE_CLOUD_TOKEN: "%s"
                  TAPSTATE_CLOUD_CLUSTER_ID: "%s"
                  TAPSTATE_CLOUD_ATLAS_URI: "%s"
                volumes:
                  - tapstate-runtime:/var/lib/tapstate
            """.formatted(RUNTIME_IMAGE, controlPlaneBaseUrl, token, clusterId, atlasUri);

        String sidecarDependency = """
                depends_on:
                  tapstate-mongo:
                    condition: service_healthy
            """;

        String mongo = """
              tapstate-mongo:
                image: %s
                container_name: tapstate-mongo
                restart: unless-stopped
                command: ["--replSet", "tapstate-rs"]
                volumes:
                  - tapstate-mongo:/data/db
                healthcheck:
                  test: ["CMD-SHELL", "mongosh --quiet --eval 'try { rs.status() } catch (e) { rs.initiate() }; db.getSiblingDB(\\"admin\\").hello().isWritablePrimary || quit(1)'"]
                  interval: 5s
                  timeout: 10s
                  retries: 30
            """.formatted(SIDECAR_MONGO_IMAGE);

        String volumes = """
            volumes:
              tapstate-runtime:
                name: tapstate-runtime
              tapstate-mongo:
                name: tapstate-mongo
            """;

        return header
            + runtime
            + (sidecar ? sidecarDependency : "")
            + (sidecar ? mongo : "")
            + volumes;
    }

    /**
     * Render the Nginx site configuration for the Cluster domain.
     * <p>
     * TLS is terminated directly with the centrally managed certificate files
     * (see {@link #REMOTE_NGINX_CERT_PATH} and {@link #REMOTE_NGINX_KEY_PATH});
     * plain HTTP is redirected to HTTPS. The certificate files must be in place
     * before Nginx loads this configuration.
     */
    public String nginxConf(String domain) {
        return """
            # Cluster reverse proxy - generated by the control plane, do not edit by hand.
            server {
                listen 80;
                listen [::]:80;
                server_name %s;

                # Every plain-HTTP request is upgraded; TLS terminates on 443 below.
                location / {
                    return 301 https://$host$request_uri;
                }
            }

            server {
                listen 443 ssl;
                listen [::]:443 ssl;
                server_name %s;

                ssl_certificate %s;
                ssl_certificate_key %s;
                ssl_protocols TLSv1.2 TLSv1.3;
                ssl_prefer_server_ciphers off;
                ssl_session_cache shared:TapstateTLS:10m;
                ssl_session_timeout 1d;

                location / {
                    proxy_pass http://127.0.0.1:8080;
                    proxy_http_version 1.1;
                    proxy_set_header Host $host;
                    proxy_set_header X-Real-IP $remote_addr;
                    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
                    proxy_set_header X-Forwarded-Proto $scheme;

                    # Long-lived connections used by the console streaming endpoints.
                    proxy_set_header Upgrade $http_upgrade;
                    proxy_set_header Connection "upgrade";
                    proxy_read_timeout 300s;
                    proxy_send_timeout 300s;
                    proxy_buffering off;
                }
            }
            """.formatted(domain, domain, REMOTE_NGINX_CERT_PATH, REMOTE_NGINX_KEY_PATH);
    }

    /**
     * Render the Nginx http-context tuning file. Generated Cluster hostnames are
     * long enough to exceed the platform default {@code server_names_hash_bucket_size},
     * which makes {@code nginx -t} fail without raising the bucket.
     */
    public String nginxHttpConf() {
        return """
            # HTTP-level tuning - generated by the control plane, do not edit by hand.
            server_names_hash_bucket_size 128;
            """;
    }
}
